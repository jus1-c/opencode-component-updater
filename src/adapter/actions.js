/** Write the schema-1 result the Go checker reads back. */
export async function writeCheckResult(path, result) {
  if (!path) fail("OPENCODE_UPDATER_CHECK_RESULT is not set");
  await writeFile(path, `${JSON.stringify({ schemaVersion: 1, ...result }, null, 2)}\n`, "utf8");
}

export function statusFor(current, latest) {
  return current === latest ? "current" : "update-available";
}

/** Check a component whose identity is the remote default-branch HEAD. */
export async function checkGitHead({ target, remote, sourceSubdir = "" }) {
  const root = sourceSubdir ? join(target, sourceSubdir) : target;
  const current = await localGitHead(root);
  if (!current) fail(`${root} is not a git checkout`);
  if (await localGitDirty(root)) {
    return { status: "manual-only", summary: "Dirty git worktree", current };
  }
  const latest = await resolveGitHead(remote);
  return {
    status: statusFor(current, latest),
    summary: current === latest ? current : `${current} -> ${latest}`,
    current,
    latest,
    sourceCommit: latest,
  };
}

/**
 * Check a Python component pinned to an exact git commit inside requirements.in.
 */
export async function checkRequirementCommit({ target, remote, distribution }) {
  const requirements = join(target, "requirements.in");
  const current = await requirementCommit(requirements, distribution);
  if (!current) fail(`${requirements} has no exact commit pin for ${distribution}`);
  const latest = await resolveGitHead(remote);
  return {
    status: statusFor(current, latest),
    summary: current === latest ? current : `${current} -> ${latest}`,
    current,
    latest,
    sourceCommit: latest,
  };
}

/**
 * Check a Python component pinned to a git release tag. Identity is the commit
 * the tag points at, so a moving branch cannot change what gets installed.
 */
export async function checkRequirementRelease({ target, remote, distribution }) {
  const requirements = join(target, "requirements.in");
  const current = await requirementCommit(requirements, distribution);
  if (!current) fail(`${requirements} has no exact commit pin for ${distribution}`);
  const { tag, commit } = await resolveGitRelease(remote);
  return {
    status: statusFor(current, commit),
    summary: current === commit ? `${tag} (${current})` : `${current} -> ${commit} (${tag})`,
    current,
    latest: commit,
    sourceCommit: commit,
  };
}

