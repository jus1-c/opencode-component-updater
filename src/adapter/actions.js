import { cp, mkdir, mkdtemp, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { assertLinkFree, installedPackageVersion, installedSelfVersion, localGitDirty, localGitHead, requirementCommit, requirementPin, treeFingerprint } from "./inspect.js";
import { resolveGitHead, resolveGitRelease, resolveNpmRelease, resolvePypiRelease } from "./resolve.js";
